    def execute(
        self,
        skill_id: str,
        user_input: Dict[str, Any],
        max_tokens: int = 8000
    ) -> SkillResult:
        """
        执行一个 skill

        Args:
            skill_id: skill ID
            user_input: 用户输入参数（与 skill 的 fields 对应）
            max_tokens: 最大输出 token 数

        Returns:
            SkillResult
        """
        try:
            # 1. 获取 prompt 模板
            if skill_id not in self.skill_prompts:
                return SkillResult(
                    success=False,
                    output="",
                    credits_used=0,
                    error=f"未找到 skill: {skill_id}"
                )

            prompt_template = self.skill_prompts[skill_id]

            # 2. 填充用户输入
            try:
                filled_prompt = prompt_template.format(**user_input)
            except KeyError as e:
                return SkillResult(
                    success=False,
                    output="",
                    credits_used=0,
                    error=f"缺少必需参数: {e}"
                )

            # 2.5 PII 脱敏：真值换成占位符再发出去。网关的内容安全审查会拦手机号
            # 等敏感信息（403 prompt_review_blocked），且不该把用户 PII 传给第三方
            # LLM。模型会在输出里保留占位符，第 5 步换回真值。
            from pii import mask_pii, unmask_pii
            filled_prompt, pii_map = mask_pii(filled_prompt)

            # 3. 调用 LLM
            # 推理型模型（deepseek-*、qwen 等）的思维链也算 completion token，
            # max_tokens 给小了会 finish_reason=length、content 为空（静默截断）。
            # 关掉思维链省 token；参数不认识会被网关静默忽略，不会报错。
            extra_body = {}
            model_name = (self.model or "").lower()
            if model_name.startswith("deepseek"):
                extra_body = {"thinking": {"type": "disabled"}}
            elif model_name.startswith("qwen") or self.llm_provider == "bailian":
                extra_body = {"enable_thinking": False}

            response = self.client.chat.completions.create(
                model=self.model,
                messages=[
                    {"role": "system", "content": "你是一位专业的 AI 助手，严格按照用户要求完成任务。"},
                    {"role": "user", "content": filled_prompt}
                ],
                max_tokens=max_tokens,
                temperature=0.7,
                extra_body=extra_body or None,
            )

            choice = response.choices[0]
            output = (choice.message.content or "").strip()
            if not output:
                # 空返回：多半是推理型模型把 max_tokens 烧在思维链上被截断
                return SkillResult(
                    success=False,
                    output="",
                    credits_used=0,
                    error=f"模型返回内容为空（finish_reason={choice.finish_reason}）。"
                          f"可能是 max_tokens 不够，推理型模型的思维链也算 token。",
                )

            # 5. 还原 PII：把占位符换回用户的真实信息
            output = unmask_pii(output, pii_map)

            # 4. 计算积分消耗（简化估算）
            tokens_used = response.usage.total_tokens
            credits_used = max(10, tokens_used // 100)  # 每 100 tokens = 1 积分

            return SkillResult(
                success=True,
                output=output,
                credits_used=credits_used,
                truncated=(choice.finish_reason == "length"),
            )

        except Exception as e:
            return SkillResult(
                success=False,
                output="",
                credits_used=0,
                error=f"执行失败: {str(e)}"
            )

